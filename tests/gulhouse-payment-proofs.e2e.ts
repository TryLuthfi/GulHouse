import { test } from '@e2e-dev/web';
import { expect } from 'e2e';

const master = '/master/index.php';
async function login(app: any, screen: any, browser: any, user: string) {
  await app.open(`${master}/login`);
  await screen.getByLabel('Username').fill(user);
  await screen.getByLabel('Password').fill(process.env.GULHOUSE_E2E_PASS ?? '');
  await screen.getByRole('button', 'Login').click();
  await expect(browser).toHaveURL(/dashboard/);
}
test('payment transfer proof upload download readonly role delete and payment cleanup', { timeout: 600000 }, async ({ app, screen, browser }) => {
  const admin = process.env.GULHOUSE_E2E_USER ?? 'codex_trial';
  const stamp = String(Date.now());
  await login(app, screen, browser, admin);
  await app.open(`${master}/payments?q=DEMO%20Penghuni%201`);
  const add = browser.locator('[data-open-modal^="#payment-add-"]').first();
  const selector = await add.getAttribute('data-open-modal');
  await add.click();
  await browser.locator(`${selector} [name="payment_date"]`).fill('2026-11-01');
  await browser.locator(`${selector} [name="amount"]`).fill('1000');
  await browser.locator(`${selector} [name="payment_type"]`).selectOption({ value: 'other' });
  await browser.locator(`${selector} [name="method"]`).fill('Transfer synthetic proof');
  await browser.locator(`${selector} [name="reference_no"]`).fill(`PROOF-${stamp}`);
  await browser.locator(`${selector} button[type="submit"]`).click();
  await browser.locator('[data-confirm-save]').click();
  await expect(browser.locator('.notice.success')).toBeVisible();
  const ownRowIndex = await browser.evaluate((reference) => {
    const field = Array.from(document.querySelectorAll('.modal [name="reference_no"]')).find(input => (input as HTMLInputElement).value === reference);
    const modal = field?.closest('.modal');
    return Array.from(document.querySelectorAll('tbody tr')).findIndex(row => Array.from(row.querySelectorAll('[data-open-modal]')).some(button => button.getAttribute('data-open-modal') === `#${modal?.id}`));
  }, `PROOF-${stamp}`);
  expect(ownRowIndex, 'payment row selected by its unique reference').toBeGreaterThanOrEqual(0);
  const ownRow = browser.locator(`tbody tr:nth-child(${ownRowIndex + 1})`);
  const link = ownRow.getByRole('link', 'Bukti Transfer');
  const proofPage = await link.getAttribute('href');
  const deletePayment = await ownRow.getByRole('button', 'Hapus').getAttribute('data-delete-url');
  await link.click();
  await expect.poll(async () => await browser.locator('body').textContent()).toContain(`PROOF-${stamp}`);
  await browser.locator('[name="proof_file"]').setInputFiles('tests/fixtures/payment-proof-invalid.txt');
  await screen.getByRole('button', 'Upload Bukti').click();
  await expect(browser.locator('.notice.error')).toBeVisible();
  await browser.locator('[name="proof_file"]').setInputFiles('tests/fixtures/payment-proof-valid.pdf');
  await browser.locator('[name="description"]').fill(`Synthetic bank proof ${stamp}`);
  await screen.getByRole('button', 'Upload Bukti').click();
  await expect(browser.locator('.notice.success')).toBeVisible();
  const download = browser.locator('tbody tr').first().getByRole('link', 'Unduh Bukti');
  const downloadUrl = await download.getAttribute('href');
  const artifact = await browser.waitForDownload(() => download.click());
  expect(artifact.suggestedFilename).toMatch(/bukti-pembayaran-\d+\.pdf/);
  await app.open(`${master}/dashboard`);
  await browser.locator('[data-logout-form] button[data-logout]').click();
  await login(app, screen, browser, 'demo_viewer');
  await browser.goto(String(proofPage));
  await expect(browser.locator('[name="proof_file"]')).not.toBeVisible();
  await expect(screen.getByRole('button', 'Hapus Bukti')).not.toBeVisible();
  const readonlyDownload = await browser.waitForDownload(() => screen.getByRole('link', 'Unduh Bukti').click());
  expect(readonlyDownload.suggestedFilename).toMatch(/\.pdf$/);
  await app.open(`${master}/dashboard`);
  await browser.locator('[data-logout-form] button[data-logout]').click();
  await login(app, screen, browser, admin);
  await browser.goto(String(proofPage));
  await screen.getByRole('button', 'Hapus Bukti').click();
  await expect(browser.locator('.notice.success')).toBeVisible();
  await expect(screen.getByRole('link', 'Unduh Bukti')).not.toBeVisible();
  await browser.locator('[name="proof_file"]').setInputFiles('tests/fixtures/payment-proof-valid.pdf');
  await screen.getByRole('button', 'Upload Bukti').click();
  await expect(browser.locator('.notice.success')).toBeVisible();
  const removedLink = await screen.getByRole('link', 'Unduh Bukti').getAttribute('href');
  await screen.getByRole('link', 'Kembali ke Pembayaran').click();
  const removal = browser.locator(`button[data-delete-url="${deletePayment}"]`);
  await removal.click();
  await browser.locator('[data-confirm-delete]').click();
  await expect(browser.locator('.notice.success')).toBeVisible();
  await browser.goto(String(removedLink));
  await expect(screen.getByRole('heading', '404')).toBeVisible();
  expect(downloadUrl).not.toBe(null);
});
