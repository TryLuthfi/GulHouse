export function uiLabel(value: unknown): string {
  const text = String(value ?? "");
  const key = text
    .trim()
    .toLowerCase()
    .replace(/[\s-]+/g, "_");
  return copy[key] ?? text;
}

// Translate enum captions while keeping identifiers and FK display names intact.
export function uiOptions(options: any): any {
  if (!options || Array.isArray(options) || typeof options !== "object")
    return options;
  return Object.fromEntries(
    Object.entries(options).map(([key, value]) => [
      key,
      typeof value === "string" ? uiLabel(value) : value,
    ]),
  );
}
